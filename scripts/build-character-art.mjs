// Freeze the approved procedural artwork into native Swift data. No runtime JavaScript or image loading.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const source=readFileSync(new URL('scripts/site/characters/sprites.js',root),'utf8');
const {models,sprite}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const colors=['#14241d','#243e31','#40634a','#60e99a','#b5efc8','#f5ebd3','#cfccae','#f4c477','#cb884a','#e6a15f'];
const letters='abcdefghij';
const names={'opus-5':'opus','opus-55':'opus55','fable-5':'fable','fable-51':'fable51','sonnet-55':'sonnet','haiku-45':'haiku'};
let output='// Generated by scripts/build-character-art.mjs from the approved literary guild. Do not edit by hand.\n';
output+='// Palette codes correspond to CharacterInk in DesignSystem/Theme/Tokens.swift.\n';
output+='enum ModelCharacterAtlas {\n    static let palette: [UInt32] = ['+colors.map(c=>'0x'+c.slice(1).toUpperCase()).join(', ')+']\n    static let rows: [ModelCharacter.Edition: [[String]]] = [\n';
for(const model of models){
 output+=`        .${names[model.id]}: [\n`;
 for(const [frame,action] of [[0,'idle'],[7,'signature'],[18,'idle'],[30,'idle']]){
  const rows=sprite(model,frame,action).map(row=>row.map(c=>{if(c===null)return '.';const i=colors.indexOf(c);if(i<0)throw Error(c);return letters[i]}).join(''));
  if(rows.length!==40||rows.some(row=>row.length!==40))throw Error('Bad sprite dimensions');
  output+='            [\n'+rows.map(row=>`                "${row}",`).join('\n')+'\n            ],\n';
 }
 output+='        ],\n';
}
// A neutral robot preserves unknown-provider handling. This original fallback is not a model capability claim.
const old=JSON.parse(readFileSync(new URL('scripts/site/characters/assets/current-sprites.json',root),'utf8'));
const robot=old.other||['.....c......','.....a......','..aaaaaaaa..','..abbaabba..','..abdaadba..','..aaaaaaaa..','...a.aa.a...','.aaaaaaaaaa.','.a.aaaaaa.a.','...aaaaaa...','...a....a...','..aa....aa..'];
const grid=Array.from({length:40},()=>Array(40).fill('.')),mapping={a:'d',b:'f',c:'c',d:'a'};
robot.forEach((row,y)=>[...row].forEach((ch,x)=>{for(let dy=0;dy<2;dy++)for(let dx=0;dx<2;dx++)grid[12+y*2+dy][8+x*2+dx]=mapping[ch]||'.'}));
output+='        .other: [\n            [\n'+grid.map(row=>`                "${row.join('')}",`).join('\n')+'\n            ],\n        ],\n    ]\n}\n';
const destination=new URL('Sources/ClepsoApp/Views/Details/ModelCharacterAtlas.swift',root);
if(process.argv.includes('--check')){if(readFileSync(destination,'utf8')!==output)throw Error('Native artwork is stale; run node scripts/build-character-art.mjs');console.log('Native character atlas matches approved website drawings.');}
else{writeFileSync(destination,output);console.log('Wrote '+fileURLToPath(destination));}
