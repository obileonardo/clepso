def compose(base, accent):
    """A base letter with a mark centred over it (or under it, for the cedilla)."""
    btop, brows = G[base]
    mrows = ACCENTS[accent]
    bw, mw = len(brows[0]), len(mrows[0])
    w = max(bw, mw)
    bl, ml = (w - bw) // 2, (w - mw + (1 if (w - mw) % 2 and bw % 2 == 0 else 0)) // 2
    if accent == "cedilla":
        mtop = -1
        ml = (w - mw) // 2 + 1 if bw >= 4 else 0
    elif btop >= CAP:                       # capital or ascender
        mtop = 7 + len(mrows) if accent != "ring" else 9
    else:
        mtop = 7 if len(mrows) == 2 else (6 if len(mrows) == 1 else 8)
    top = max(btop, mtop)
    bottom = min(btop - len(brows) + 1, mtop - len(mrows) + 1)
    grid = [["."] * w for _ in range(top - bottom + 1)]
    for r, row in enumerate(brows):
        for c, ch in enumerate(row):
            if ch == "#":
                grid[top - (btop - r)][bl + c] = "#"
    for r, row in enumerate(mrows):
        for c, ch in enumerate(row):
            if ch == "#":
                grid[top - (mtop - r)][ml + c] = "#"
    return top, ["".join(r) for r in grid]


for ch, (base, accent) in ACCENTED.items():
    G[ch] = compose(base, accent)

# Spacing glyphs: (advance in px). Figure space matches the digits.
SPACES = {" ": 4, " ": 4, " ": 6, " ": 2, " ": 1}

# Kerning is computed, not listed: a pair tightens by 1 px when, after tightening, no inked pixel of one glyph touches
# the other (8-connected), i.e. the open shapes (T, L, Y, F, P, r, quotes, period) tuck in and nothing ever merges.
# Figures are never kerned: they are tabular.
KERN_EXCLUDE = set("0123456789%+−=±")


def profile(ch):
    """{row: (leftmost x, rightmost x)} of a glyph's ink."""
    top, rows = G[ch]
    out = {}
    for r, row in enumerate(rows):
        xs = [i for i, c in enumerate(row) if c == "#"]
        if xs:
            out[top - r] = (min(xs), max(xs))
    return out


def auto_kern():
    chars = [c for c in G if c not in KERN_EXCLUDE]
    prof = {c: profile(c) for c in chars}
    pairs = []
    for a in chars:
        pa, adv = prof[a], len(G[a][1][0]) + 1
        for b in chars:
            pb = prof[b]
            gap = None
            for y, (_, ra) in pa.items():
                for yy in (y - 1, y, y + 1):
                    if yy in pb:
                        d = adv + pb[yy][0] - ra - 1
                        gap = d if gap is None else min(gap, d)
            if gap is not None and gap >= 2:
                pairs.append((a, b, -1))
    return pairs
