"""Clepso Pixel: the display face, drawn here pixel by pixel.

Grid: one pixel = 100 font units, em = 10 pixels. Cap height and ascenders 7 px, x-height 5 px, descenders 2 px,
accents up to 10 px. Each entry is (top, rows): `top` is the y of the first row (baseline = 0, y up), rows run top
to bottom, '#' is ink. Advance = bitmap width + 1 px. Digits, %, +, −, = and figure space share one width (6 px), so
numbers that tick never shift.

Design brief (design/brand/NOTES.md §Type): every figure must be unmistakable at a glance. 0 carries a dot (O does
not), 5 has a square shoulder (S is chamfered), 1 has a flag and foot (I has two serifs, l has a tail), 8 is round
on both sides (B is flat on the left), 6/G and 9/g differ in their spurs.
"""

